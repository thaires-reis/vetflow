-- 1. TABELA: USUARIOS
-- Armazena os usuários que podem acessar o sistema.

CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);


-- 2. TABELA: TUTORES
-- Armazena os dados dos responsáveis pelos animais.

CREATE TABLE tutores (
    id_tutor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    cpf VARCHAR(11) UNIQUE,
    telefone VARCHAR(20) NOT NULL,
    email VARCHAR(150),
    endereco VARCHAR(200)
);


-- 3. TABELA: ANIMAIS
-- Armazena os animais cadastrados na clínica.
-- Cada animal pertence a um tutor.

CREATE TABLE animais (
    id_animal INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tutor INTEGER NOT NULL,
    nome VARCHAR(100) NOT NULL,
    especie VARCHAR(50) NOT NULL,
    raca VARCHAR(80),
    sexo VARCHAR(10),
    data_nascimento DATE,
    peso NUMERIC(6,2),

    CONSTRAINT fk_animais_tutores
        FOREIGN KEY (id_tutor)
        REFERENCES tutores (id_tutor),

    CONSTRAINT chk_sexo_animal
        CHECK (sexo IS NULL OR sexo IN ('M', 'F')),

    CONSTRAINT chk_peso_animal
        CHECK (peso IS NULL OR peso > 0)
);


-- 4. TABELA: VETERINARIOS
-- Armazena os profissionais veterinários.
-- Um veterinário pode estar vinculado a um usuário.

CREATE TABLE veterinarios (
    id_veterinario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER UNIQUE,
    nome VARCHAR(100) NOT NULL,
    crmv VARCHAR(30) UNIQUE NOT NULL,
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_veterinarios_usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES usuarios (id_usuario)
);


-- 5. TABELA: ESPECIALIDADES
-- Armazena as especialidades veterinárias.

CREATE TABLE especialidades (
    id_especialidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) UNIQUE NOT NULL,
    descricao VARCHAR(200)
);


-- 6. TABELA: VETERINARIO_ESPECIALIDADES
-- Relaciona veterinários e especialidades.
-- Permite que um veterinário tenha várias especialidades e que uma especialidade pertença a vários veterinários.


CREATE TABLE veterinario_especialidades (
    id_veterinario INTEGER NOT NULL,
    id_especialidade INTEGER NOT NULL,

    CONSTRAINT pk_veterinario_especialidades
        PRIMARY KEY (id_veterinario, id_especialidade),

    CONSTRAINT fk_ve_veterinarios
        FOREIGN KEY (id_veterinario)
        REFERENCES veterinarios (id_veterinario),

    CONSTRAINT fk_ve_especialidades
        FOREIGN KEY (id_especialidade)
        REFERENCES especialidades (id_especialidade)
);


-- 7. TABELA: CONSULTAS
-- Armazena os agendamentos e consultas realizadas.
-- Retornos são registrados como novas consultas, vinculadas à consulta original.

CREATE TABLE consultas (
    id_consulta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_animal INTEGER NOT NULL,
    id_veterinario INTEGER NOT NULL,
    id_consulta_origem INTEGER,
    tipo_consulta VARCHAR(20) NOT NULL DEFAULT 'INICIAL',
    data_hora TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AGENDADA',
    motivo VARCHAR(200),

    CONSTRAINT fk_consultas_animais
        FOREIGN KEY (id_animal)
        REFERENCES animais (id_animal),

    CONSTRAINT fk_consultas_veterinarios
        FOREIGN KEY (id_veterinario)
        REFERENCES veterinarios (id_veterinario),

    CONSTRAINT fk_consultas_origem
        FOREIGN KEY (id_consulta_origem)
        REFERENCES consultas (id_consulta),

    CONSTRAINT chk_tipo_consulta
        CHECK (
            (tipo_consulta = 'INICIAL' AND id_consulta_origem IS NULL)
            OR
            (tipo_consulta = 'RETORNO' AND id_consulta_origem IS NOT NULL)
        ),

    CONSTRAINT chk_consulta_origem_diferente
        CHECK (
            id_consulta_origem IS NULL
            OR id_consulta_origem <> id_consulta
        ),

    CONSTRAINT chk_status_consulta
        CHECK (status IN ('AGENDADA', 'REALIZADA', 'CANCELADA'))
);


-- 8. TABELA: ATENDIMENTOS
-- Armazena o registro clínico de cada consulta.
-- Cada consulta pode possuir no máximo um atendimento.

CREATE TABLE atendimentos (
    id_atendimento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta INTEGER UNIQUE NOT NULL,
    data_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    diagnostico TEXT,
    procedimentos TEXT,
    observacoes TEXT,

    CONSTRAINT fk_atendimentos_consultas
        FOREIGN KEY (id_consulta)
        REFERENCES consultas (id_consulta)
);


-- ÍNDICE DE INTEGRIDADE DE AGENDAMENTO
-- Impede que o mesmo veterinário tenha duas consultas agendadas no mesmo horário.
-- Consultas canceladas ou já realizadas não entram nessa restrição.

CREATE UNIQUE INDEX uq_veterinario_horario_agendado
ON consultas (id_veterinario, data_hora)
WHERE status = 'AGENDADA';
